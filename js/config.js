// Защита от XSS: все данные из внешних API
// нужно прогонять через эту функцию перед вставкой в innerHTML
function esc(s) {
  return String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

